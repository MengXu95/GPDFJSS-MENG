"""Render the audited GP trees with a compact ordered-tree layout.

Run with Python after installing bigtree, matplotlib, pandas, and pyparsing.
The input tree-audit.json is generated by analyze_learned_trees.py.
"""

import hashlib
import json
import shutil
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.colors import to_hex, to_rgb
from matplotlib.patches import Circle, FancyBboxPatch, PathPatch
from matplotlib.path import Path as DrawingPath
from bigtree import Node, reingold_tilford
import pandas as pd
from pyparsing import nested_expr


ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "tree-case-study"
INK = "#000000"
GREEN = "#000000"
NEUTRAL = "#64748B"
BLUE = "#2563EB"
ORANGE = "#F97316"


def tint(colour, opacity):
    return to_hex(tuple(1 - opacity * (1 - channel) for channel in to_rgb(colour))).upper()


PREFERENCE_FILLS = {"Pone": tint(BLUE, .35), "Ptwo": tint(ORANGE, .35)}
PALETTE = {
    "A": (BLUE, tint(BLUE, .15)),
    "B": (ORANGE, tint(ORANGE, .15)),
    "U": (INK, "#F3F3F3"),
}
OPERATORS = {"+", "-", "*", "/", "Min", "Max"}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def make_tree(expression):
    values = nested_expr().parse_string(expression, parse_all=True).as_list()
    assert len(values) == 1

    def build(value, position="r"):
        if isinstance(value, str):
            assert value not in OPERATORS
            return Node(position, token=value)
        assert len(value) == 3 and value[0] in OPERATORS
        return Node(position, token=value[0], children=[build(value[1], position + ".0"), build(value[2], position + ".1")])

    return build(values[0])


def plot_trees(report, output=OUTPUT):
    sequencing = [entry for entry in report["Trees"] if entry["Role"] == "sequencing"]
    assert [entry["Scenario"] for entry in sequencing] == [1, 3, 5]
    sources = report["SourcesSHA256"]
    assert all(digest(Path(path)) == checksum for path, checksum in sources.items())
    output.mkdir(exist_ok=True)
    backup = output / "before-side-by-side"
    for name in ["learned-sequencing-trees.pdf", "learned-sequencing-trees.png", "tree-figure-nodes.csv", "figure-validation.json"]:
        source = output / name
        if source.exists() and not (backup / name).exists():
            backup.mkdir(exist_ok=True)
            shutil.copy2(source, backup / name)

    roots, spans, depths = [], [], []
    for entry in sequencing:
        root = make_tree(entry["Expression"])
        reingold_tilford(root, sibling_separation=1.8, subtree_separation=2.5, level_separation=1.8, reverse=True)
        nodes = [root, *root.descendants]
        assert len(nodes) == entry["Nodes"]
        for node in nodes:
            if node.children:
                assert len(node.children) == 2 and node.children[0].x < node.x < node.children[1].x
                assert abs(node.x - (node.children[0].x + node.children[1].x) / 2) < 1e-10
        roots.append(root)
        spans.append(max(node.x for node in nodes) - min(node.x for node in nodes))
        depths.append(max(node.y for node in nodes))
    maximum_span = max(spans)
    plt.rcParams.update({"font.family": "serif", "font.serif": ["Times New Roman", "DejaVu Serif"],
                         "font.size": 12, "text.color": GREEN, "pdf.fonttype": 42, "ps.fonttype": 42})
    figure = plt.figure(figsize=(14, 8.2))
    grid = figure.add_gridspec(2, 1, height_ratios=[max(depths[:2]) + 2.2, depths[2] + 2.2])
    upper = grid[0].subgridspec(1, 2, width_ratios=[span + 2.6 for span in spans[:2]], wspace=.08)
    axes = [figure.add_subplot(upper[0]), figure.add_subplot(upper[1]), figure.add_subplot(grid[1])]
    figure.subplots_adjust(left=.025, right=.985, top=.945, bottom=.12, hspace=.25)
    aliases = {"WKR": "WR", "TRANT": "TR", "Pone": r"$w_1$", "Ptwo": r"$w_2$", "*": r"$\times$", "-": r"$-$", "/": r"$/$"}
    plotted, patches, annotations = [], [], []
    for panel, entry, root, span, depth, axis in zip(["a", "b", "c"], sequencing, roots, spans, depths, axes):
        nodes = [root, *root.descendants]
        by_path = {node.node_name: node for node in nodes}
        selected = {}
        for label, module in report["Modules"].items():
            for occurrence in module["Occurrences"]:
                if occurrence["Scenario"] == entry["Scenario"]: selected[occurrence["Path"]] = label
        panel_span = span if panel in ["a", "b"] else maximum_span
        shift = (panel_span - span) / 2 - min(node.x for node in nodes)
        positions = {node.node_name: (node.x + shift, -node.y) for node in nodes}

        def module_at(path):
            matching = [(position, label) for position, label in selected.items() if path == position or path.startswith(position + ".")]
            return max(matching, key=lambda value: len(value[0]))[1] if matching else ""

        for node in nodes:
            path = node.node_name
            horizontal, vertical = positions[path]
            module = module_at(path)
            colour, face = PALETTE["U" if module.startswith("U") else module] if module else (NEUTRAL, "#FFFFFF")
            operator = node.token in OPERATORS
            preference = node.token in ["Pone", "Ptwo"]
            if node.parent:
                parent_path = node.parent.node_name
                parent_horizontal, parent_vertical = positions[parent_path]
                middle = (parent_vertical + vertical) / 2
                points = [(parent_horizontal, parent_vertical - .34), (parent_horizontal, middle),
                          (horizontal, middle), (horizontal, vertical + .34)]
                path_patch = PathPatch(DrawingPath(points, [DrawingPath.MOVETO, DrawingPath.LINETO, DrawingPath.LINETO, DrawingPath.LINETO]),
                                      facecolor="none", edgecolor=INK,
                                      linewidth=1.0, capstyle="round", joinstyle="round", zorder=1)
                axis.add_patch(path_patch)
            if operator:
                patch = Circle((horizontal, vertical), .57, facecolor=face, edgecolor=INK, linewidth=1.15, zorder=3)
                font = 9.5 if node.token in ["Min", "Max"] else 12.5
            else:
                patch = FancyBboxPatch((horizontal - .70, vertical - .40), 1.40, .80,
                                      boxstyle="round,pad=.025,rounding_size=.09", facecolor=PREFERENCE_FILLS[node.token] if preference else (face if module else "white"),
                                      edgecolor=INK, linewidth=1.15 if module or preference else .8, zorder=3)
                font = 12.5 if preference else 11
            axis.add_patch(patch)
            label = axis.text(horizontal, vertical, aliases.get(node.token, node.token), ha="center", va="center", fontsize=font,
                              color=INK, zorder=4)
            patches.append((entry["Scenario"], path, patch, label))
            if path in selected:
                badge = axis.text(horizontal + .72, vertical + .65, selected[path], fontsize=9.5, fontweight="bold", ha="left", va="bottom",
                                  color=INK, bbox={"facecolor": "white", "edgecolor": "none", "pad": .2}, zorder=5)
                annotations.append((entry["Scenario"], path, badge))
            plotted.append({"Scenario": entry["Scenario"], "Path": path, "Token": node.token, "X": horizontal, "Y": vertical,
                            "Module": module, "Preference": preference})
        utilisation = {1: ".70", 3: ".80", 5: ".90"}[entry["Scenario"]]
        axis.text(0, 1.02, f"({panel}) Scenario {entry['Scenario']}" + r"  $\rho=" + utilisation + "$", transform=axis.transAxes,
                  fontsize=14, fontweight="bold", ha="left", va="bottom", color=GREEN)
        axis.text(1, 1.025, f"{entry['Nodes']} nodes", transform=axis.transAxes, fontsize=11, ha="right", va="bottom", color=INK)
        axis.plot([0, 1], [1, 1], transform=axis.transAxes, color=INK, linewidth=.8, clip_on=False)
        axis.set_xlim(-1, panel_span + 1.6)
        axis.set_ylim(-depth - .75, .85)
        axis.set_aspect("equal", adjustable="box")
        axis.axis("off")
    legend = [Line2D([0], [0], color=PALETTE["A"][0], linewidth=2, label=r"A: $100\,\mathrm{NOR}\,w_2-\mathrm{SL}$  (S1, S3)"),
              Line2D([0], [0], color=PALETTE["B"][0], linewidth=2, label=r"B: $\mathrm{W}+100w_2$  (S3, S5)"),
              Line2D([0], [0], color=INK, linewidth=2, label="U1 / U3 / U5: task-specific modules"),
              Line2D([0], [0], marker="s", color=INK, markerfacecolor=PREFERENCE_FILLS["Pone"], linewidth=0, label=r"$w_1$: objective 1"),
              Line2D([0], [0], marker="s", color=INK, markerfacecolor=PREFERENCE_FILLS["Ptwo"], linewidth=0, label=r"$w_2$: objective 2")]
    figure.legend(handles=legend, loc="lower center", bbox_to_anchor=(.5, .012), ncol=2, frameon=False, fontsize=11,
                  handlelength=2, columnspacing=2, labelspacing=.65)
    figure.canvas.draw()
    renderer = figure.canvas.get_renderer()
    for index, (scenario, path, patch, label) in enumerate(patches):
        box = patch.get_window_extent(renderer)
        extent = label.get_window_extent(renderer)
        factor = min(1., .94 * box.width / extent.width, .94 * box.height / extent.height)
        if factor < 1:
            label.set_fontsize(label.get_fontsize() * factor)
            extent = label.get_window_extent(renderer)
        assert box.contains(*extent.get_points()[0]) and box.contains(*extent.get_points()[1]), (scenario, path, "text overflow")
        for other_scenario, other_path, other_patch, _ in patches[index + 1:]:
            if scenario == other_scenario: assert not box.overlaps(other_patch.get_window_extent(renderer)), (scenario, path, other_path)
    placed_badges = []
    positions_by_key = {(entry["Scenario"], entry["Path"]): (entry["X"], entry["Y"]) for entry in plotted}
    for scenario, path, badge in annotations:
        horizontal, vertical = positions_by_key[(scenario, path)]
        obstacles = [patch.get_window_extent(renderer).expanded(1.03, 1.03) for other_scenario, _, patch, _ in patches if scenario == other_scenario]
        obstacles += [box for other_scenario, box in placed_badges if scenario == other_scenario]
        found = False
        for offset_x, offset_y, alignment in [(.72, .65, "left"), (-.72, .65, "right"), (.72, -.85, "left"), (-.72, -.85, "right"),
                                               (.72, 1.0, "left"), (-.72, 1.0, "right")]:
            badge.set_position((horizontal + offset_x, vertical + offset_y))
            badge.set_ha(alignment)
            box = badge.get_window_extent(renderer).expanded(1.08, 1.08)
            if not any(box.overlaps(obstacle) for obstacle in obstacles):
                placed_badges.append((scenario, box))
                found = True
                break
        assert found, (scenario, path, "module badge placement")
    assert len(plotted) == 139 and sum(entry["Preference"] for entry in plotted) == 14
    for suffix, options in [("pdf", {}), ("png", {"dpi": 240})]:
        figure.savefig(output / f"learned-sequencing-trees.{suffix}", bbox_inches="tight", pad_inches=.08, **options)
    plt.close(figure)
    pd.DataFrame(plotted).to_csv(output / "tree-figure-nodes.csv", index=False)
    validation = {"Nodes": 139, "Edges": 136, "PreferenceLeaves": 14, "OriginalTreeNodeCounts": [37, 31, 71],
                  "NodeLabelCollisions": 0, "ModuleBadgeCollisions": 0, "CompleteOrderedTrees": True,
                  "PanelRows": 2, "TopRowScenarios": [1, 3], "BottomRowScenario": 5,
                  "PreferenceDisplayLabels": ["w_1", "w_2"], "PreferenceTerminalScale": 100,
                  "Palette": PALETTE, "PreferenceFills": PREFERENCE_FILLS, "TextAndEdgesColour": INK,
                  "PaletteReference": "Figures7and8:objective1blue/objective2orange;sharedtintsat15percent,preferenceleavesat35percent",
                  "Layout": "bigtree Reingold-Tilford/Walker,ordered children,centred parents,equal-level alignment",
                  "Renderer": "Python matplotlib:circle operators,rounded terminal boxes,orthogonal edges",
                  "PDFSHA256": digest(output / "learned-sequencing-trees.pdf"), "PNGSHA256": digest(output / "learned-sequencing-trees.png")}
    (output / "figure-validation.json").write_text(json.dumps(validation, indent=2), encoding="utf-8")
    print("PASS:139original nodes/136edges/14preference leaves;ordered compact tree layout;no label/badge collisions;PDF/PNG generated.")
    return validation


if __name__ == "__main__":
    plot_trees(json.loads((OUTPUT / "tree-audit.json").read_text()))